import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../portal-interactions.js',import.meta.url),'utf8');
const context=vm.createContext({setTimeout,clearTimeout,console,URLSearchParams});vm.runInContext(source,context);
const {renderImmediately,routeKey}=context.PortalInteractions;
assert.equal(routeKey('#papers?page=2&direction=agent-software'),routeKey('#papers?page=3'));
assert.equal(routeKey('#news?origin=auto'),routeKey('#news?type=reports'));
assert.notEqual(routeKey('#directions?pillar=physical-ai'),routeKey('#directions?pillar=data-privacy'));
const commits=[];
renderImmediately(()=>commits.push('first'));
assert.deepEqual(commits,['first'],'Navigation renders synchronously, without waiting for an opening effect');
renderImmediately(()=>commits.push('latest'));
assert.deepEqual(commits,['first','latest']);
assert.ok(!source.includes('md-route-curtain'));
assert.ok(!source.includes('md-pointer-dot'));
assert.ok(!source.includes('md-dot-active'));
assert.ok(!source.includes("window.scrollTo({top:0"),'Page-level scrolling is owned by the central hashchange handler');
assert.ok(source.includes('IntersectionObserver'),'Long lists progressively reveal more records while scrolling');
assert.ok(source.includes('data-infinite-list'));
const html=fs.readFileSync(new URL('../legacy.html',import.meta.url),'utf8');
assert.ok(!/<script[^>]+src="portal-motion\.js/.test(html),'No page entrance animation module is loaded');
assert.ok(!/<link[^>]+href="portal-motion\.css/.test(html),'Motion styles are consolidated into the interaction layer');
const css=fs.readFileSync(new URL('../portal-interactions.css',import.meta.url),'utf8');
assert.ok(!css.includes('cursor:none'));
assert.ok(css.includes('--motion-ease:cubic-bezier(.16,1,.3,1)'));
assert.ok(css.includes('@media(prefers-reduced-motion:reduce)'));
assert.ok(css.includes('#primary-nav{overflow:visible;gap:16px;align-items:center}'));
assert.ok(css.includes('.md-nav-group{position:relative;display:flex;align-items:center;gap:3px;min-width:0;min-height:32px}'));
assert.ok(css.includes('.site-header #primary-nav>.md-nav-group>a,.site-header #primary-nav>a{display:flex;align-items:center;white-space:nowrap;font-size:16px;line-height:1.5;height:32px}'));
assert.ok(source.includes("directions:[{label:'论文资料'"));
assert.ok(!source.includes('directions:researchDirections.map'));
assert.ok(!source.includes("teams:[{label:'上传资源'"));
assert.equal((source.match(/\{label:'上传资源',href:'#upload'\}/g)||[]).length,2,'Upload belongs to the evaluation submenu definitions only');
assert.ok(source.includes('if(!items.length)continue'));
const menu=fs.readFileSync(new URL('../portal-madeo.js',import.meta.url),'utf8');
assert.ok(!menu.includes('先看测评结论，再按需要进入研究资料。'));
assert.ok(!menu.includes('<a href="#upload" data-madeo-destination>上传资源</a>'));
assert.ok(!menu.includes('<a href="#results" data-madeo-destination>评测看板</a>'));
const app=fs.readFileSync(new URL('../app.js',import.meta.url),'utf8');
assert.ok(app.includes('samePage=previousPath===next.path'));
assert.ok(app.includes("evaluationSuitePaths=new Set(['results','benchmarks','methods','upload'])"));
assert.ok(app.includes('sameEvaluationSuite=isEvaluationSuitePath(previousPath)&&isEvaluationSuitePath(next.path)'));
assert.ok(app.includes("librarySuitePaths=new Set(['papers','datasets'])"));
assert.ok(app.includes('sameLibrarySuite=isLibrarySuitePath(previousPath)&&isLibrarySuitePath(next.path)'));
assert.ok(app.includes("researchSuitePaths=new Set(['watch','news'])"));
assert.ok(app.includes('sameResearchSuite=isResearchSuitePath(previousPath)&&isResearchSuitePath(next.path)'));
assert.ok(app.includes('function captureInteractionRouteState'));
assert.ok(app.includes('state.pendingRouteScroll={left:window.scrollX,top:window.scrollY}'));
assert.ok(app.includes('scroll=state.pendingRouteScroll||'));
assert.ok(app.includes('restoreInteractionFocus(focus)'));
assert.ok(app.includes("suiteTabsSelector=sameEvaluationSuite?'[data-evaluation-tabs]':sameLibrarySuite?'[data-library-tabs]':sameResearchSuite?'[data-research-tabs]':''"));
assert.ok(app.includes('document.querySelector(suiteTabsSelector)?.getBoundingClientRect().top'));
assert.ok(app.includes('top+=nextTabs.getBoundingClientRect().top-suiteTabsTop'));
assert.ok(app.includes("window.scrollTo({left:scroll.left,top:Math.max(0,top),behavior:'instant'})"));
assert.ok(css.includes('#main{overflow-anchor:none}'));
assert.ok(css.includes('html{scrollbar-gutter:stable}'));
console.log('Navigation checks passed: immediate rendering, query continuity, stable same-route, evaluation, library and research-suite scroll/focus, normalized primary navigation, no curtain or custom cursor.');
