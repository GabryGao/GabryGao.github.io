import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync(new URL('../portal-interactions.js',import.meta.url),'utf8');
const context=vm.createContext({setTimeout,clearTimeout,console,URLSearchParams});vm.runInContext(source,context);
const {createTransitionGate,routeKey,transitionTiming}=context.PortalInteractions;
assert.ok(transitionTiming.failSafe>transitionTiming.enter+transitionTiming.hold+transitionTiming.exit+500,"The fail-safe must not cut off the slower opening sequence");
assert.equal(routeKey('#papers?page=2&direction=agent-software'),routeKey('#papers?page=3'));
assert.equal(routeKey('#news?origin=auto'),routeKey('#news?type=reports'));
assert.notEqual(routeKey('#directions?pillar=physical-ai'),routeKey('#directions?pillar=data-privacy'));
const pending=[],commits=[];let reset=0;
const gate=createTransitionGate({cover:()=>new Promise(resolve=>pending.push(resolve)),reveal:()=>Promise.resolve(),reset:()=>reset++},80);
const first=gate.run(()=>commits.push('old'));await Promise.resolve();const second=gate.run(()=>commits.push('latest'));await Promise.resolve();
pending[0]();await first;assert.deepEqual(commits,[],'A cancelled transition must not render a stale page');
pending[1]();await second;assert.deepEqual(commits,['latest']);
await gate.run(()=>commits.push('reduced-motion'),false);assert.deepEqual(commits,['latest','reduced-motion']);
const broken=createTransitionGate({cover:()=>Promise.reject(Error('unsupported')),reveal:()=>Promise.reject(Error('unsupported')),reset(){}},80);
await broken.run(()=>commits.push('fallback'));assert.equal(commits.at(-1),'fallback','A failed animation must still navigate');
const stuck=createTransitionGate({cover:()=>new Promise(()=>{}),reveal:()=>Promise.resolve(),reset(){}},15);stuck.run(()=>commits.push('timeout'));
await new Promise(resolve=>setTimeout(resolve,35));assert.equal(commits.at(-1),'timeout','An animation must not permanently cover or block a page');
assert.ok(reset>=3);console.log('Navigation checks passed: same-page query continuity, topic transitions, rapid-click cancellation, reduced motion, failed/timeout animation recovery.');
